"""Generate the filter constants shared by the C firmware and the Python reference.

Both sides read the same numbers, so a bit-exact comparison means the two
integer pipelines really match. Run this after changing PARAMS:

    python3 stm32/imu/tools/gen_tables.py

The Makefile test target checks that the committed files match this script.
"""
import math
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent

PARAMS = {
    "IMU_SAMPLE_RATE_HZ": 100,
    "IMU_SAMPLE_MS": 10,
    "IMU_LPF_CORNER_HZ": 10,       # 2nd-order Butterworth low-pass per axis
    "IMU_ALPHA_Q8": 251,           # complementary filter gyro weight, 251/256 = 0.980
    "IMU_MAX_GAP": 50,             # more missing samples than this resets the angle
    "IMU_G_LSB": 16384,            # accelerometer LSB per g at +-2 g
    "IMU_GYRO_LSB_PER_DPS": 131,   # gyro LSB per degree/second at +-250 dps
    "IMU_TILT_MDEG": 5000,         # 5 degrees away from the start pose sets TILT
    "IMU_BUMP_HIGH_NUM": 3,        # bump when |a| > 3/2 g (squared compare)
    "IMU_BUMP_LOW_NUM": 1,         # free-fall when |a| < 1/2 g
    "IMU_SPIN_MDPS": 200000,       # 200 degrees/second sets BUMP
}

Q30 = 1 << 30


def biquad_coeffs():
    fs = PARAMS["IMU_SAMPLE_RATE_HZ"]
    fc = PARAMS["IMU_LPF_CORNER_HZ"]
    k = math.tan(math.pi * fc / fs)
    norm = 1.0 / (1.0 + math.sqrt(2.0) * k + k * k)
    b0 = k * k * norm
    b1 = 2.0 * b0
    b2 = b0
    a1 = 2.0 * (k * k - 1.0) * norm
    a2 = (1.0 - math.sqrt(2.0) * k + k * k) * norm
    return [round(v * Q30) for v in (b0, b1, b2, a1, a2)]


def atan_table():
    # atan(i/256) in millidegrees, i = 0..256, used with linear interpolation.
    return [round(math.atan(i / 256.0) * 180000.0 / math.pi) for i in range(257)]


def c_text():
    lines = [
        "/* Generated by stm32/imu/tools/gen_tables.py. Do not edit by hand. */",
        "#ifndef IMU_TABLES_H",
        "#define IMU_TABLES_H",
        "",
    ]
    for name, value in PARAMS.items():
        lines.append(f"#define {name} {value}")
    b0, b1, b2, a1, a2 = biquad_coeffs()
    lines += [
        "",
        "/* 2nd-order Butterworth low-pass, Q30 fixed point. a1 and a2 are the",
        "   denominator terms of 1 + a1 z^-1 + a2 z^-2 (a1 is negative). */",
        f"#define IMU_B0 {b0}",
        f"#define IMU_B1 {b1}",
        f"#define IMU_B2 {b2}",
        f"#define IMU_A1 ({a1})",
        f"#define IMU_A2 ({a2})",
        "",
        "/* atan(i/256) in millidegrees, i = 0..256. */",
        "static const int32_t IMU_ATAN_TABLE[257] = {",
    ]
    table = atan_table()
    for start in range(0, len(table), 8):
        chunk = ", ".join(str(v) for v in table[start:start + 8])
        lines.append(f"    {chunk},")
    lines += ["};", "", "#endif", ""]
    return "\n".join(lines)


def py_text():
    lines = [
        '"""Generated by stm32/imu/tools/gen_tables.py. Do not edit by hand."""',
        "",
    ]
    for name, value in PARAMS.items():
        lines.append(f"{name} = {value}")
    b0, b1, b2, a1, a2 = biquad_coeffs()
    lines += [
        f"IMU_B0 = {b0}",
        f"IMU_B1 = {b1}",
        f"IMU_B2 = {b2}",
        f"IMU_A1 = {a1}",
        f"IMU_A2 = {a2}",
        f"IMU_ATAN_TABLE = {atan_table()!r}",
        "",
    ]
    return "\n".join(lines)


def outputs():
    return {
        ROOT / "src" / "imu_tables.h": c_text(),
        ROOT / "reference" / "imu_tables.py": py_text(),
    }


def main(check=False):
    stale = []
    for path, text in outputs().items():
        if check:
            if not path.exists() or path.read_text() != text:
                stale.append(str(path))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    if stale:
        print("stale generated files:", ", ".join(stale))
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(check="--check" in sys.argv))
