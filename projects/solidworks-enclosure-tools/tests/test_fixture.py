import json,pathlib,pytest
from fixture_check import check
ROOT=pathlib.Path(__file__).resolve().parents[1]
P=json.loads((ROOT/'specs/fixture.json').read_text())

def test_fixture_all_shrinkage_cases_have_positive_fit():
    r=check(P)
    assert r['passes']
    assert min(x['worst_total_gap_x_mm'] for x in r['shrinkage'])>0
    assert r['minimum_wall_mm']==pytest.approx(6)

def test_deliberately_broken_wall_edge_stack():
    assert 'wall' in check(dict(P,floor_mm=.8))['flags']
    assert 'hole_edge' in check(dict(P,hole_x_mm=53))['flags']
    assert 'fit_stack' in check(dict(P,clearance_per_side_mm=.05))['flags']

def test_native_fixture_is_closed_and_matches_solidworks():
    import trimesh
    m=trimesh.load_mesh(ROOT/'cad/fixture/FX-001_enclosure_nest_B.STL')
    assert m.is_watertight
    assert m.volume==pytest.approx(92448.982727171,rel=.01)
    assert m.extents==pytest.approx([108,88,14],abs=.001)

def test_real_slicing_record_matches_mesh_profile_and_gcode():
    import hashlib
    record=json.loads((ROOT/'reports/fixture/slicing-record.json').read_text())
    for name,digest in record['sha256'].items():
        assert hashlib.sha256((ROOT/name).read_bytes()).hexdigest()==digest
    gcode=(ROOT/'cad/fixture/FX-001_enclosure_nest_B.gcode').read_text()
    assert 'generated by PrusaSlicer 2.7.2' in gcode
    assert record['layer_changes']==70
    assert 'G1 X' in gcode
