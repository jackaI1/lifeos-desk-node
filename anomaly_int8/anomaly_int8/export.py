"""Write the int8 model as C headers and render the comparison report."""
import numpy as np

from . import quant

HEADER_NOTE = '/* Generated by `python -m anomaly_int8 run`. Do not edit by hand. */\n'


def _array(values):
    values = [int(v) for v in np.ravel(values)]
    lines = []
    for start in range(0, len(values), 16):
        lines.append('    ' + ', '.join(str(v) for v in values[start:start + 16]) + ',')
    return '\n'.join(lines)


def write_model_header(path, qmodel):
    parts = [HEADER_NOTE, '#ifndef ANOMALY_INT8_MODEL_PARAMS_H\n#define ANOMALY_INT8_MODEL_PARAMS_H\n',
             '#include <stdint.h>\n#include "anomaly_int8.h"\n']
    for layer in qmodel.layers:
        n = layer.index
        parts.append(f'static const int8_t anomaly_w{n}[{layer.weight.size}] = {{\n'
                     f'{_array(layer.weight)}\n}};\n')
        parts.append(f'static const int32_t anomaly_b{n}[{layer.bias.size}] = {{\n'
                     f'{_array(layer.bias)}\n}};\n')
    parts.append('static const anomaly_layer_t anomaly_layers[ANOMALY_LAYERS] = {\n')
    for layer in qmodel.layers:
        n = layer.index
        parts.append(
            f'    {{{layer.weight.shape[1]}, {layer.weight.shape[0]}, '
            f'{layer.in_zero_point}, {layer.out_zero_point}, '
            f'{layer.multiplier}u, {layer.shift}, {1 if layer.relu else 0}, '
            f'anomaly_w{n}, anomaly_b{n}}},\n')
    parts.append('};\n')
    parts.append('static const int32_t anomaly_score_weights[ANOMALY_INPUTS] = {\n'
                 f'    {", ".join(str(int(w)) for w in qmodel.score_weights)}\n}};\n')
    parts.append(f'#define ANOMALY_THRESHOLD {qmodel.threshold}\n')
    parts.append('#endif\n')
    path.write_text(''.join(parts))


def write_vectors_header(path, qmodel, raw, int_inputs):
    """Test vectors from raw readings, so the C input quantizer is checked too."""
    temperature, humidity = raw
    inputs = np.asarray(int_inputs, dtype=np.int64)
    outputs = quant.run_layers(qmodel.layers, inputs)
    scores = quant.integer_scores(qmodel.layers, inputs, qmodel.score_weights)
    flags = (scores > qmodel.threshold).astype(int)
    raw_both = np.concatenate([temperature, humidity], axis=1)
    count = len(inputs)
    text = [HEADER_NOTE, '#ifndef ANOMALY_INT8_TEST_VECTORS_H\n#define ANOMALY_INT8_TEST_VECTORS_H\n',
            '#include <stdint.h>\n',
            f'#define ANOMALY_VECTOR_COUNT {count}\n',
            'static const int32_t anomaly_vec_raw[ANOMALY_VECTOR_COUNT * 8] = {\n'
            f'{_array(raw_both)}\n}};\n',
            'static const int8_t anomaly_vec_input[ANOMALY_VECTOR_COUNT * 8] = {\n'
            f'{_array(inputs)}\n}};\n',
            'static const int8_t anomaly_vec_output[ANOMALY_VECTOR_COUNT * 8] = {\n'
            f'{_array(outputs)}\n}};\n',
            'static const int32_t anomaly_vec_score[ANOMALY_VECTOR_COUNT] = {\n'
            f'{_array(scores)}\n}};\n',
            'static const int anomaly_vec_flag[ANOMALY_VECTOR_COUNT] = {\n'
            f'{_array(flags)}\n}};\n',
            '#endif\n']
    path.write_text(''.join(text))


def _pct(value):
    return 'n/a' if value is None else f'{100 * value:.0f} %'


def render_report(results, layers):
    f, i, c = results['float'], results['int8'], results['comparison']
    lines = [
        '# Anomaly detector: float model against int8',
        '',
        'Generated by `python -m anomaly_int8 run`. The log is '
        f"`{results['log']['source']}`, with {results['log']['readings']} readings "
        f"({results['log']['windows']} windows of four). Training uses normal windows only; "
        'the threshold uses normal validation windows; the test uses the last 15 % of the log.',
        '',
        'The held-out test has injected faults (spikes, stuck readings, humidity jumps and '
        'dropouts), so these numbers are for the simulated faults I put in, not for faults '
        'I have seen on the real sensor yet.',
        '',
        '| Model | Accuracy | Precision | Recall | False alarms | Threshold | Memory |',
        '|---|---|---|---|---|---|---|',
        f"| Float32 (PyTorch weights) | {f['accuracy']:.4f} | {f['precision']:.3f} | "
        f"{f['recall']:.3f} | {f['false_alarm_rate']:.4f} | {f['threshold']:.2f} | "
        f"{f['bytes_float32']} bytes |",
        f"| int8 (C integer routine) | {i['accuracy']:.4f} | {i['precision']:.3f} | "
        f"{i['recall']:.3f} | {i['false_alarm_rate']:.4f} | {i['threshold']} | "
        f"{i['int8_bytes']} bytes |",
        '',
        f"Accuracy loss from quantization: {c['accuracy_loss']:+.4f}. Decisions agree on "
        f"{100 * c['decision_agreement']:.2f} % of test windows. The reconstructed outputs differ by "
        f"{c['output_mean_abs_gap_units']:.3f} units on average (max {c['output_max_abs_gap_units']:.0f}); "
        'one unit is 0.1 C or 0.5 %RH.',
        '',
        '## Recall by injected fault (test windows)',
        '',
        '| Fault | Test windows | Float32 recall | int8 recall |',
        '|---|---|---|---|',
    ]
    for name, row in results['per_fault'].items():
        lines.append(f"| {name.replace('_', ' ')} | {row['windows']} | "
                     f"{_pct(row['float_recall'])} | {_pct(row['int8_recall'])} |")
    lines += [
        '',
        'A stuck sensor repeats its last reading for four samples, and each window is four '
        'readings, so a stuck window looks like a calm room to this model. Catching it needs a '
        'longer window or a check on variance, which I have not added.',
        '',
        '## Quantization per layer',
        '',
        '| Layer | Input scale | Input zero point | Weight scale | Output scale | Output zero point | Multiplier m0 | Shift r | ReLU |',
        '|---|---|---|---|---|---|---|---|---|',
    ]
    for layer in layers:
        lines.append(f'| {layer.index} | {layer.in_scale:.6g} | {layer.in_zero_point} | '
                     f'{layer.weight_scale:.6g} | {layer.out_scale:.6g} | {layer.out_zero_point} | '
                     f'{layer.multiplier} | {layer.shift} | {"yes" if layer.relu else "no"} |')
    lines += ['',
              'The input layer uses one device unit per step (0.1 C for each temperature, '
              '0.5 %RH for each humidity), so the zero point is 0. The last layer reuses the input '
              'scale and zero point, so the score is a plain integer sum.',
              '']
    return '\n'.join(lines)
