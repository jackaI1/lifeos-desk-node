"""Collect timing, area and power from each OpenROAD run and write the sweep table.

For every variant the script reads the metrics that the flow writes (JSON
metric files under logs/ and reports/), falling back to the text reports. It
writes build/openroad/results.json and docs/openroad-sweep.md. It exits 1 when
the chosen constraint has negative setup slack, which is the CI gate.
"""
import argparse
import json
import sys
from pathlib import Path

SLACK_KEYS = ['finish__timing__setup__ws']
AREA_KEYS = ['finish__design__instance__area']
POWER_KEYS = ['finish__power__total']


def _from_json(files, keys):
    for path in files:
        if path.suffix != '.json':
            continue
        try:
            data = json.loads(path.read_text())
        except (OSError, ValueError):
            continue
        for key in keys:
            if key in data and isinstance(data[key], (int, float)):
                return float(data[key])
    return None


def measure(out, variant):
    # The final metrics are written by the 6_report step into logs/<variant>/6_report.json.
    files = sorted((out / 'logs' / variant).glob('6_report.json'))
    slack = _from_json(files, SLACK_KEYS)
    area = _from_json(files, AREA_KEYS)
    power = _from_json(files, POWER_KEYS)
    return {'worst_setup_slack_ns': slack, 'area_um2': area, 'power_w': power}


def markdown(rows, chosen):
    lines = [
        '# OpenROAD sweep: sensor path on Nangate45',
        '',
        'Generated by `flow/collect.py` from the CI run. Each row is a full OpenROAD run '
        '(Yosys synthesis, floorplan, placement, clock tree, global and detailed routing).',
        '',
        '| Clock period | Core utilization | Worst setup slack | Cell area | Power | Meets timing |',
        '|---|---|---|---|---|---|',
    ]
    for row in rows:
        def fmt(value, spec):
            return 'n/a' if value is None else format(value, spec)
        met = 'n/a' if row['worst_setup_slack_ns'] is None else (
            'yes' if row['worst_setup_slack_ns'] >= 0 else 'no')
        lines.append(f"| {row['period_ns']} ns | {row['utilization_pct']} % | "
                     f"{fmt(row['worst_setup_slack_ns'], '.3f')} ns | "
                     f"{fmt(row['area_um2'], '.1f')} um^2 | {fmt(row['power_w'], '.3e')} W | {met} |")
    lines += ['', f"CI gate: the chosen constraint is {chosen['period_ns']} ns at "
              f"{chosen['utilization_pct']} % utilization, and it must meet timing.", '']
    return '\n'.join(lines)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('out', type=Path)
    parser.add_argument('--periods', nargs='+', required=True)
    parser.add_argument('--utils', nargs='+', required=True)
    parser.add_argument('--chosen-period', default='2.0')
    parser.add_argument('--chosen-util', default='30')
    parser.add_argument('--docs', type=Path, default=Path('/work/docs/openroad-sweep.md'))
    args = parser.parse_args(argv)
    rows = []
    for period in args.periods:
        for util in args.utils:
            variant = f"p{period.replace('.', '')}_u{util}"
            metrics = measure(args.out, variant)
            rows.append({'variant': variant, 'period_ns': float(period),
                         'utilization_pct': int(util), **metrics})
    chosen = next((r for r in rows if r['period_ns'] == float(args.chosen_period)
                   and r['utilization_pct'] == int(args.chosen_util)), None)
    (args.out / 'results.json').write_text(json.dumps(rows, indent=2) + '\n')
    if args.docs.parent.exists():
        args.docs.write_text(markdown(rows, chosen or {'period_ns': args.chosen_period,
                                                        'utilization_pct': args.chosen_util}))
    for row in rows:
        print(json.dumps(row))
    if chosen is None or chosen['worst_setup_slack_ns'] is None:
        print('error: chosen constraint has no slack value; see the flow logs', file=sys.stderr)
        return 1
    if chosen['worst_setup_slack_ns'] < 0:
        print(f"error: timing violated at the chosen constraint: slack {chosen['worst_setup_slack_ns']} ns",
              file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
